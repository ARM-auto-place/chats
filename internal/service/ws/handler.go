package ws

import (
	"context"
	"time"

	"github.com/gofiber/fiber/v2"
	"github.com/gofiber/websocket/v2"
	"github.com/google/uuid"

	"github.com/ARM-auto-place/chats/internal/client"
	chatService "github.com/ARM-auto-place/chats/internal/service"
)

// wsPath must stay in sync with the design spec's WS-протокол section and
// with deploy/nginx/conf.d/wk.amctechgroup.ru.conf's chat location — that
// location is the only one forwarding the Upgrade/Connection headers a
// WebSocket handshake needs, so this path has to live under /api/v1/chat/.
const (
	wsPath           = "/api/v1/chat/ws"
	handshakeTimeout = 5 * time.Second
)

// RegisterRoute wires the WS upgrade route onto app. Unlike the REST routes
// (generated by tg into internal/transport/jsonRPC), this one is
// hand-written: it's a persistent connection, not a request/response call
// the generator's model fits.
func RegisterRoute(app *fiber.App, hub *Hub, backend chatService.ChatBackend, accessClient client.AccessClient) {
	app.Use(wsPath, func(ctx *fiber.Ctx) error {
		if !websocket.IsWebSocketUpgrade(ctx) {
			return fiber.ErrUpgradeRequired
		}
		userID, err := uuid.Parse(ctx.Query("userID"))
		if err != nil || userID == uuid.Nil {
			return fiber.NewError(fiber.StatusBadRequest, "userID query param required")
		}
		ctx.Locals("userID", userID)
		return ctx.Next()
	})

	app.Get(wsPath, websocket.New(func(conn *websocket.Conn) {
		userID, _ := conn.Locals("userID").(uuid.UUID)
		handleConnection(conn, userID, hub, backend, accessClient)
	}))
}

// handleConnection blocks for the connection's lifetime: gofiber releases
// conn as soon as the websocket.New callback returns, so it waits for
// WritePump too, not only ReadPump.
func handleConnection(conn *websocket.Conn, userID uuid.UUID, hub *Hub, backend chatService.ChatBackend, accessClient client.AccessClient) {
	ctx, cancel := context.WithTimeout(context.Background(), handshakeTimeout)
	defer cancel()

	isBot := userID == chatService.BotUserID
	isAdmin := false
	if !isBot {
		var err error
		isAdmin, err = accessClient.CheckAccess(ctx, userID, chatService.RoleCodeAdmin)
		if err != nil {
			hub.logger.Error().Err(err).Str("userID", userID.String()).Str("event", "ws_access_check").Msg("chat ws: access check failed")
			_ = conn.Close()
			return
		}
	}

	chatID := uuid.Nil
	if !isAdmin && !isBot {
		chat, err := backend.EnsureOwnerChat(ctx, userID)
		if err != nil {
			hub.logger.Error().Err(err).Str("userID", userID.String()).Str("event", "ws_owner_chat").Msg("chat ws: failed to resolve owner chat")
			_ = conn.Close()
			return
		}
		chatID = chat.ID
	}

	client := NewClient(userID, isAdmin, isBot, chatID, conn, hub, backend, hub.logger)
	select {
	case hub.Register <- client:
	case <-hub.done:
		client.stopWorkers()
		client.close("hub_stopped")
		return
	}

	writeDone := make(chan struct{})
	go func() {
		defer close(writeDone)
		client.WritePump()
	}()
	client.ReadPump()
	<-writeDone
}
